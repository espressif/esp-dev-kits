import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TEMPLATE_PATH = REPO_ROOT / ".gitlab" / "ci" / "docs_child.yml.tpl"
CONF_COMMON = REPO_ROOT / "docs" / "conf_common.py"

# Keep this list aligned with docs/conf_common.py idf_targets.
# "esp32" is intentionally first: longer target names are matched before the
# generic esp32 fallback.
KNOWN_TARGETS = [
    "esp32",
    "esp32s2",
    "esp32s3",
    "esp32c3",
    "esp32c6",
    "esp32h2",
    "esp32c2",
    "esp32p4",
    "esp32c5",
    "esp32c61",
    "esp32s31",
    "other",
]

TOP_LEVEL_RST = re.compile(r"^docs/(en|zh_CN)/[^/]+\.rst$")
RELEASE_BRANCH = re.compile(r"^release/v")
VERSION_TAG = re.compile(r"^v\d+\.\d+(\.\d+)?($|-)")

# These inputs are not tied to one chip, but every target build uses them.
SHARED_DOC_FILES = {
    "docs/conf_common.py",
    "docs/en/conf.py",
    "docs/zh_CN/conf.py",
    "docs/requirements.txt",
    "docs/setuptools.requirements.txt",
}

NO_TARGETS_PIPELINE = """\
# Generated by tools/ci/select_doc_targets.py. No documentation target changed.
workflow:
  rules:
    - when: always

stages:
  - build_doc

variables:
  ESP_IDF_DOC_ENV_IMAGE: "$CI_DOCKER_REGISTRY/esp-idf-doc-env-v5.4:1-1"

no_doc_targets:
  stage: build_doc
  image: $ESP_IDF_DOC_ENV_IMAGE
  tags:
    - build_docs
  script:
    - echo "No documentation targets matched the changed files. Nothing to build."
"""


def _add(found, seen, target):
    if target not in seen:
        seen.add(target)
        found.add(target)


def targets_for_file(path):
    """Return the doc targets affected by one changed path.

    Matching follows the previous build_docs before_script, including the
    board-name exceptions. ESP32-S31 and ESP32-C61 are matched on their own
    because their names contain a shorter target (esp32s3, esp32c6).
    """
    found = set()
    seen = set()

    if TOP_LEVEL_RST.match(path):
        for target in KNOWN_TARGETS:
            _add(found, seen, target)
    else:
        flattened = path.replace("-", "")
        matched_specific = False

        if re.search(r"esp32-s31", path) or re.search(r"esp32s31", flattened):
            _add(found, seen, "esp32s31")
            matched_specific = True
        elif re.search(r"esp32-c61", path) or re.search(r"esp32c61", flattened):
            _add(found, seen, "esp32c61")
            matched_specific = True
        else:
            for target in KNOWN_TARGETS:
                if target == "esp32":
                    continue
                if re.search(target, flattened):
                    _add(found, seen, target)
                    matched_specific = True

        if not matched_specific and re.search(r"esp32", flattened):
            _add(found, seen, "esp32")

    if "esp-wrover-kit" in path:
        _add(found, seen, "esp32")
    if "esp8684" in path:
        _add(found, seen, "esp32c2")
    if "esp-module-prog" in path or "esp-prog" in path:
        _add(found, seen, "other")
    if "esp-vocat" in path or "esp-dualkey" in path:
        _add(found, seen, "esp32s3")
    if "esp-mosaico" in path:
        _add(found, seen, "esp32s31")
    if "esp-sensairshuttle" in path:
        _add(found, seen, "esp32c5")
    if "eol" in path:
        _add(found, seen, "esp32")
        _add(found, seen, "esp32s2")
        _add(found, seen, "esp32s3")

    return found


def ordered_targets(found):
    return [target for target in KNOWN_TARGETS if target in found]


def has_build_label(labels):
    return any(part.strip().lower() == "build" for part in labels.split(","))


def is_protected_ref(ref_name, branch, tag):
    if ref_name == "master":
        return True
    if branch and RELEASE_BRANCH.match(branch):
        return True
    if tag and VERSION_TAG.match(tag):
        return True
    return False


def select_targets(files, ref_name="", branch="", tag="", labels=""):
    """Return (targets, reason). targets is empty when nothing should build."""
    if has_build_label(labels):
        return list(KNOWN_TARGETS), "build label"
    if is_protected_ref(ref_name, branch, tag):
        return list(KNOWN_TARGETS), "protected ref"
    if any(path in SHARED_DOC_FILES for path in files):
        return list(KNOWN_TARGETS), "shared doc config"
    found = set()
    for path in files:
        if not path.startswith("docs/"):
            continue
        # Templates and extensions can affect every target even if their name
        # contains a chip name. Unknown documentation paths also build all.
        if path.startswith("docs/") and (
            "/_templates/" in path
            or path.startswith(("docs/_static/js/", "docs/_static/css/"))
            or path.endswith((".py", ".sh"))
        ):
            return list(KNOWN_TARGETS), "shared doc config"
        matched = targets_for_file(path)
        if path.startswith("docs/") and not matched:
            return list(KNOWN_TARGETS), "unmapped doc path"
        found.update(matched)
    return ordered_targets(found), "git diff"


def render_pipeline(targets):
    if not targets:
        return NO_TARGETS_PIPELINE
    template = TEMPLATE_PATH.read_text()
    if "@DOCTGT_LIST@" not in template:
        raise RuntimeError("docs_child.yml.tpl is missing @DOCTGT_LIST@")
    rendered = template.replace("@DOCTGT_LIST@", json.dumps(targets))
    if "@DOCTGT_LIST@" in rendered:
        raise RuntimeError("failed to substitute documentation targets")
    return rendered


def _changed_files_from_git():
    base = os.environ.get("CI_MERGE_REQUEST_DIFF_BASE_SHA", "").strip()
    head = os.environ.get("CI_COMMIT_SHA", "").strip() or "HEAD"
    if not base:
        raise RuntimeError(
            "CI_MERGE_REQUEST_DIFF_BASE_SHA is empty; cannot tell which documentation targets changed"
        )
    probe = subprocess.run(
        ["git", "cat-file", "-e", "{0}^{{commit}}".format(base)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if probe.returncode != 0:
        fetch = subprocess.run(["git", "fetch", "--depth=1", "origin", base])
        if fetch.returncode != 0:
            raise RuntimeError("failed to fetch diff base {0}".format(base))
    diff = subprocess.run(
        ["git", "diff", "--name-only", "--no-renames", "-z", base, head, "--"],
        check=False,
        text=True,
        capture_output=True,
    )
    if diff.returncode != 0:
        detail = (diff.stderr or diff.stdout or "git diff failed").strip()
        raise RuntimeError(detail)
    return [path for path in diff.stdout.split("\0") if path]


def choose_targets_from_env():
    ref_name = os.environ.get("CI_COMMIT_REF_NAME", "")
    branch = os.environ.get("CI_COMMIT_BRANCH", "")
    tag = os.environ.get("CI_COMMIT_TAG", "")
    labels = os.environ.get("CI_MERGE_REQUEST_LABELS", "")
    if has_build_label(labels) or is_protected_ref(ref_name, branch, tag):
        return select_targets([], ref_name=ref_name, branch=branch, tag=tag, labels=labels)

    files = _changed_files_from_git()
    print("Changed files:")
    for path in files:
        print("  {0}".format(path))
    return select_targets(files, ref_name=ref_name, branch=branch, tag=tag, labels=labels)


def _targets_in_conf_common():
    text = CONF_COMMON.read_text()
    match = re.search(r"^idf_targets\s*=\s*\[([^\]]*)\]", text, re.M)
    if not match:
        raise AssertionError("idf_targets not found in docs/conf_common.py")
    return re.findall(r"'([^']+)'", match.group(1))


def run_self_test():
    assert _targets_in_conf_common() == KNOWN_TARGETS

    cases = {
        "docs/zh_CN/esp32-s3-lcd-ev-board/user_guide.rst": ["esp32s3"],
        "docs/en/esp32-s31-korvo-1/index.rst": ["esp32s31"],
        "docs/en/index/esp32s31-index.inc": ["esp32s31"],
        "docs/en/esp32-c61-devkitc-1/user_guide_v1.0.rst": ["esp32c61"],
        "docs/en/esp32-c6-devkitm-1/user_guide.rst": ["esp32c6"],
        "docs/en/esp32-p4-function-ev-board/user_guide.rst": ["esp32p4"],
        "docs/zh_CN/esp32-c3-lcdkit/user_guide.rst": ["esp32c3"],
        "docs/en/esp32-devkitc/user_guide.rst": ["esp32"],
        "docs/en/esp-dualkey/user_guide.rst": ["esp32s3"],
        "docs/en/esp-vocat/user_guide_v1.2.rst": ["esp32s3"],
        "docs/en/esp-sensairshuttle/index.rst": ["esp32c5"],
        "docs/_static/esp-mosaico/esp-mosaico-coreboard-front.png": ["esp32s31"],
        "docs/en/esp-prog/user_guide.rst": ["other"],
        "docs/zh_CN/esp-module-prog-sub-02/user_guide.rst": ["other"],
        "docs/en/esp8684-devkitm-1/index.rst": ["esp32c2"],
        "docs/en/eol/eol-boards.rst": ["esp32", "esp32s2", "esp32s3"],
        "docs/requirements.txt": [],
        "examples/esp32-s3-lcd-ev-board/examples/smart_panel/main/main.c": ["esp32s3"],
    }
    for path, expected in cases.items():
        got = ordered_targets(targets_for_file(path))
        if got != expected:
            raise AssertionError("{0}: expected {1}, got {2}".format(path, expected, got))

    combined, reason = select_targets(
        [
            "docs/zh_CN/esp32-s3-lcd-ev-board/user_guide.rst",
            "docs/en/esp32-c3-lcdkit/index.rst",
        ]
    )
    assert combined == ["esp32s3", "esp32c3"], combined
    assert reason == "git diff"

    top, _ = select_targets(["docs/en/index.rst"])
    assert top == KNOWN_TARGETS

    shared, reason = select_targets(["docs/requirements.txt"])
    assert shared == KNOWN_TARGETS
    assert reason == "shared doc config"

    for path in (
        "docs/en/_templates/layout.html",
        "docs/_static/js/redirect_404.js",
        "docs/_static/css/esp32s3-theme.css",
        "docs/feedback_doc_ids.py",
        "docs/check_lang_folder_sync.sh",
        "docs/en/new-board/user_guide.rst",
    ):
        assert select_targets([path])[0] == KNOWN_TARGETS, path

    for path in (
        ".gitlab/ci/docs_child.yml.tpl",
        "tools/ci/select_doc_targets.py",
        ".gitlab-ci.yml",
    ):
        empty, reason = select_targets([path])
        assert empty == [], (path, reason)

    ci_and_doc, reason = select_targets(
        [
            ".gitlab/ci/docs.yml",
            "docs/en/esp32-devkitc/user_guide.rst",
        ]
    )
    assert ci_and_doc == ["esp32"], reason

    labeled, reason = select_targets(
        ["docs/requirements.txt"], labels="docs, build"
    )
    assert labeled == KNOWN_TARGETS
    assert reason == "build label"

    protected, reason = select_targets([], ref_name="master")
    assert protected == KNOWN_TARGETS
    assert reason == "protected ref"

    release, reason = select_targets([], branch="release/v1.2")
    assert release == KNOWN_TARGETS
    assert reason == "protected ref"

    feature, reason = select_targets(
        ["docs/en/esp32-s3-lcd-ev-board/index.rst"],
        ref_name="feature/lcd",
    )
    assert feature == ["esp32s3"]
    assert reason == "git diff"

    one = render_pipeline(["esp32s3"])
    assert 'DOCTGT: ["esp32s3"]' in one
    assert "build_docs_html" in one
    assert "local: '.gitlab/ci/deploy_docs.yml'" in one
    assert "local: '.gitlab/ci/publish_docs_to_cdp.yml'" in one
    assert "DOC_TARGETS: '[\"esp32s3\"]'" in one
    assert "@DOCTGT_LIST@" not in one

    several = render_pipeline(["esp32s3", "esp32c3"])
    assert 'DOCTGT: ["esp32s3", "esp32c3"]' in several
    assert "DOC_TARGETS: '[\"esp32s3\", \"esp32c3\"]'" in several

    full = render_pipeline(KNOWN_TARGETS)
    assert 'DOCTGT: ' + json.dumps(KNOWN_TARGETS) in full
    assert "DOC_TARGETS: '" + json.dumps(KNOWN_TARGETS) + "'" in full

    empty = render_pipeline([])
    assert "no_doc_targets" in empty
    assert "build_docs_html" not in empty
    assert "deploy" not in empty

    print("select_doc_targets self-test passed")


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", help="Path of the generated child pipeline YAML")
    parser.add_argument("--self-test", action="store_true", help="Run matching checks and exit")
    args = parser.parse_args(argv)

    if args.self_test:
        run_self_test()
        if not args.output:
            return 0

    if not args.output:
        parser.error("pass --output, --self-test, or both")

    targets, reason = choose_targets_from_env()
    printable = " ".join(targets) if targets else "(none)"
    print("Documentation targets ({0}): {1}".format(reason, printable))
    Path(args.output).write_text(render_pipeline(targets))
    print("Wrote {0}".format(args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
