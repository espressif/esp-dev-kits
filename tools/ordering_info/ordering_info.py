def cmd_report(args, config):
    boards, records = collect(config, args.boards)

    cats = {k: [] for k in ('will_update_inc', 'up_to_date', 'no_include',
                             'manual', 'no_api', 'excluded')}

    for record in records:
        for lang, r in record['results'].items():
            if r['has_manual']:
                cats['manual'].append((record, r))
            elif not r['inc_up_to_date']:
                cats['will_update_inc'].append((record, r))
            else:
                cats['up_to_date'].append((record, r))
            if r['include_idx'] is None and not r['has_manual']:
                cats['no_include'].append((record, r))

    for record in records:
        if record['excluded']:
            cats['excluded'].append((record, None))
        elif not record['api_name'] or not record['variants']:
            cats['no_api'].append((record, None))

    print(f'Live API: {config["api_url"]}\n')

    def show(title, items, detail=None):
        print(f'{title} ({len(items)})')
        for item in items:
            record, r = item
            p = rel(r['path']) if r else record['folder']
            print(f'  {p}')
            if detail and r:
                for note in detail(record, r):
                    print(f'      - {note}')
        print()

    show('inc will be written or updated', cats['will_update_inc'])
    show('inc up to date', cats['up_to_date'])
    show('guide does not include ordering-info.inc (add the include by hand if needed)', cats['no_include'])

    print(f'Hand-written table → inc generated alongside, rst not modified ({len(cats["manual"])})')
    for record, r in cats['manual']:
        print(f'  {rel(r["path"])}')
        for note in r['manual_diff'] or ['matches the API']:
            print(f'      - {note}')
    print()

    show('No API match, skipped', cats['no_api'])
    show('EOL or other-target board, skipped', cats['excluded'])

    if not args.boards:
        covered = {r['api_name'] for r in records if r['api_name']}
        missing_guides = sorted(n for n in boards if n not in covered)
        print(f'In the product API but no user guide here ({len(missing_guides)})')
        for n in missing_guides:
            print(f'  {n}')
        print()

    return 0


def cmd_apply(args, config):
    if args.boards and args.since:
        sys.exit('use either --board or --since, not both')

    board_args = args.boards
    if args.since:
        changed = git_changed_files(args.since, working_tree=True)
        print(f'Changed files since {args.since}: {len(changed)}')
        if is_global_ordering_change(changed):
            sys.exit(
                'Generator, config, or exclusion list changed; '
                'run apply without --since to refresh every board.'
            )
        folders = sorted(board_folders_from_paths(changed))
        if not folders:
            print('No development-board docs changed; nothing to apply.')
            return 0
        print('Refreshing boards: ' + ', '.join(folders))
        board_args = folders

    _, records = collect(config, board_args)

    if board_args:
        for record in records:
            if record['excluded']:
                sys.exit(f'{record["folder"]} is an EOL or other-target board; skipped by design.')
            if not record['results']:
                sys.exit(
                    f'{record["folder"]}: no match in the product API. '
                    f'Check the folder/API name or add name_overrides in config.json.'
                )

    inc_written = []
    for record in records:
        for r in record['results'].values():
            if not r['inc_up_to_date']:
                write_inc(r)
                inc_written.append(rel(r['inc_path']))

    print(f'{len(inc_written)} inc file(s) written:')
    for p in inc_written:
        print(f'  {p}')
    return 0


def cmd_hook(args, config):
    """Refresh inc files for board guide paths passed by pre-commit."""
    folders = sorted(board_folders_from_paths(args.paths))
    if not folders:
        return 0

    print('Refreshing ordering information for: ' + ', '.join(folders))
    _, records = collect(config, folders)
    written = []
    warnings = []
    for record in records:
        if record['excluded']:
            continue
        if not record['results']:
            warnings.append(
                f'{record["folder"]}: no API match; check the folder name or name_overrides')
            continue
        for result in record['results'].values():
            if not result['inc_up_to_date']:
                write_inc(result)
                written.append(rel(result['inc_path']))

    for warning in warnings:
        print(f'warning: {warning}')
    if written:
        print('Generated files changed; stage them and commit again:')
        for path in written:
            print(f'  git add {path}')
        return 1
    print('Ordering information is up to date.')
    return 0


def expand_includes(path, depth=0):
    """Yield (source_path, lineno, text) for a guide with .. include:: resolved."""
    if depth > 5:
        return
    for lineno, line in enumerate(path.read_text(encoding='utf-8').split('\n'), 1):
        match = re.match(r'\s*\.\.\s+include::\s+(\S+)', line)
        if match:
            target = (path.parent / match.group(1)).resolve()
            if target.exists() and target.suffix in ('.inc', '.rst'):
                yield from expand_includes(target, depth + 1)
                continue
        yield (path, lineno, line)


def check_title_levels(path):
    """Report headings whose underline character is used at an inconsistent depth.

    Mirrors how docutils assigns section levels, so it catches the
    "Title level inconsistent" build failure before Sphinx runs.
    """
    items = list(expand_includes(path))
    stack, depths, errors = [], {}, []
    for i in range(len(items) - 1):
        source, lineno, line = items[i]
        title = line.strip()
        under = items[i + 1][2].strip()
        if not title or len(under) < 3 or len(under) < display_width(title):
            continue
        if under[0] not in UNDERLINE_CHARS or set(under) != {under[0]}:
            continue
        char = under[0]
        if char in stack:
            stack = stack[:stack.index(char) + 1]
        else:
            stack.append(char)
        depth = len(stack)
        if depths.setdefault(char, depth) != depth:
            errors.append(f'{rel(source)}:{lineno}: title level inconsistent: "{title}" '
                          f'is at depth {depth} but "{char}" was first used at '
                          f'depth {depths[char]}')
    return errors


def git_changed_files(since, working_tree=False):
    """Return repo-relative paths changed between ``since`` and HEAD.

    With ``working_tree=True``, include unstaged, staged, and untracked files
    relative to ``since`` (for local ``apply --since``).
    """
    spec = since if working_tree else f'{since}...HEAD'
    cmd = ['git', '-C', str(REPO_ROOT), 'diff', '--name-only', '-z', spec]
    try:
        out = subprocess.check_output(cmd, stderr=subprocess.PIPE)
    except subprocess.CalledProcessError:
        subprocess.check_call(
            ['git', '-C', str(REPO_ROOT), 'fetch', '--depth=1', 'origin', since],
        )
        out = subprocess.check_output(cmd)
    paths = [p for p in out.decode().split('\0') if p]
    if working_tree:
        extra = subprocess.check_output(
            ['git', '-C', str(REPO_ROOT), 'ls-files', '--others', '--exclude-standard', '-z'],
        )
        paths.extend(p for p in extra.decode().split('\0') if p)
    return paths


def is_global_ordering_change(paths):
    for path in paths:
        for prefix in GLOBAL_CHECK_PATHS:
            if path == prefix.rstrip('/') or path.startswith(prefix):
                return True
    return False


def board_folders_from_paths(paths):
    folders = set()
    for path in paths:
        match = DOCS_BOARD_PATH.match(path)
        if match and match.group(1) not in NON_BOARD_FOLDERS:
            folders.add(match.group(1))
    return folders


def cmd_check(args, config):
    scope = None
    if args.since:
        changed = git_changed_files(args.since)
        print(f'Changed files since {args.since}: {len(changed)}')
        if is_global_ordering_change(changed):
            print('Generator, config, or exclusion list changed; checking all boards.')
        else:
            scope = board_folders_from_paths(changed)
            if not scope:
                print('No development-board docs changed; skipping.')
                return 0
            print('Checking boards: ' + ', '.join(sorted(scope)))

    _, records = collect(config, sorted(scope) if scope is not None else None)

    errors, warnings = [], []
    for record in records:
        for lang, r in record['results'].items():
            if r['has_manual']:
                if r['manual_diff']:
                    warnings.append(
                        f'{rel(r["path"])}: hand-written table differs from the API '
                        f'({len(r["manual_diff"])} difference(s)). '
                        f'See {rel(r["inc_path"])} for the API version.')
            elif not r['inc_up_to_date']:
                errors.append(
                    f'{rel(r["inc_path"])}: inc file is missing or stale '
                    f'(run "apply --board {record["folder"]}" or "apply --since origin/master")')
            if r['include_idx'] is not None:
                errors.extend(check_title_levels(r['path']))
        if not record['api_name'] and not record['excluded'] and record['variants'] == []:
            warnings.append(f'{record["folder"]}: no match in the product API')

    for w in warnings:
        print(f'warning: {w}')
    for e in errors:
        print(f'error: {e}')

    if errors:
        print(f'\n{len(errors)} error(s). Run "ordering_info.py apply --since origin/master".')
        return 1
    if scope is not None:
        print(f'\nChanged boards are in sync ({len(warnings)} warning(s)).')
    else:
        print(f'\nAll ordering information inc files are in sync ({len(warnings)} warning(s)).')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='command', required=True)
    report_p = sub.add_parser('report')
    report_p.add_argument(
        '--board', action='append', dest='boards', metavar='FOLDER',
        help='Only this docs folder (repeatable).',
    )
    report_p.set_defaults(handler=cmd_report)
    apply_p = sub.add_parser('apply')
    apply_p.add_argument(
        '--board', action='append', dest='boards', metavar='FOLDER',
        help='Only this docs folder (repeatable). '
             'A folder name or a path such as docs/en/esp32-c6-devkitc-1.',
    )
    apply_p.add_argument(
        '--since', metavar='REF',
        help='Only boards whose docs changed since this git ref '
             '(includes uncommitted files).',
    )
    apply_p.set_defaults(handler=cmd_apply)
    check_p = sub.add_parser('check')
    check_p.add_argument(
        '--since', metavar='REF',
        help='Only check boards whose docs changed since this git ref. '
             'If the generator, config, or exclusion list changed, all boards are checked.',
    )
    check_p.set_defaults(handler=cmd_check)
    hook_p = sub.add_parser('hook')
    hook_p.add_argument('paths', nargs='*', help='Changed guide paths from pre-commit.')
    hook_p.set_defaults(handler=cmd_hook)
    args = parser.parse_args()
    return args.handler(args, load_config())


if __name__ == '__main__':
    sys.exit(main())
