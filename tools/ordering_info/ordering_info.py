VERSION_RE = re.compile(r'user_guide[-_]v?(\d+(?:\.\d+)*)\.rst$')


def _folders_from_index(index_path):
    """Return the set of doc folder names referenced in a toctree index file."""
    if not index_path.exists():
        return set()
    text = index_path.read_text(encoding='utf-8')
    return set(re.findall(r'<\.\.\/([^/>]+)\/index>', text) +
               re.findall(r'\b([a-z][a-z0-9-]+(?:&[0-9]+)?)/index\.html\b', text))


def eol_folders():
    return _folders_from_index(EOL_INDEX)


def other_folders():
    return _folders_from_index(OTHER_INDEX)


def latest_guide(folder):
    candidates = sorted(folder.glob('user_guide*.rst'))
    if not candidates:
        return None
    plain = folder / 'user_guide.rst'
    if plain in candidates:
        return plain

    def version_key(path):
        m = VERSION_RE.search(path.name)
        return tuple(int(p) for p in m.group(1).split('.')) if m else (0,)

    return max(candidates, key=version_key)


def discover_boards(config):
    overrides = config.get('name_overrides', {})
    excluded = (set(config.get('exclude_folders', [])) |
                eol_folders() | other_folders())

    records = []
    for folder in sorted((DOCS_DIR / 'en').iterdir()):
        if not folder.is_dir() or folder.name == 'eol':
            continue
        guide = latest_guide(folder)
        if guide is None:
            continue

        paths = {}
        for lang in LANGS:
            candidate = DOCS_DIR / lang / folder.name / guide.name
            if candidate.exists():
                paths[lang] = candidate

        records.append({
            'folder': folder.name,
            'guide_name': guide.name,
            'paths': paths,
            'api_name': overrides.get(folder.name) or folder.name,
            'variants': [],
            'excluded': folder.name in excluded,
        })
    return records


