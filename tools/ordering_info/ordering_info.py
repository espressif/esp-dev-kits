def rel(path):
    return path.relative_to(REPO_ROOT).as_posix()


def board_arg_to_folder(value):
    """Accept a docs folder name or a path under docs/<lang>/<folder>/."""
    posix = Path(value).as_posix().strip('/')
    match = DOCS_BOARD_PATH.match(posix + '/')
    if match:
        return match.group(1)
    return posix.split('/')[-1]


def filter_records(records, board_args):
    """Return records for ``--board`` values, or all records if none given."""
    if not board_args:
        return records
    wanted = [board_arg_to_folder(b) for b in board_args]
    by_folder = {record['folder']: record for record in records}
    missing = [name for name in wanted if name not in by_folder]
    if missing:
        sys.exit('unknown board folder: ' + ', '.join(missing))
    return [by_folder[name] for name in wanted]


def collect(config, board_args=None):
    """Fetch live API data and analyze all guides or selected board folders."""
    records = filter_records(discover_boards(config), board_args)

    if board_args:
        boards = {}
        fallback_boards = None
        for record in records:
            if record['excluded']:
                continue
            variants = fetch_api(config, record['api_name'])
            if not variants:
                # Tolerate catalog data issues such as leading/trailing spaces
                # in an API name while keeping the normal single-board request.
                if fallback_boards is None:
                    fallback_boards = group_by_board(fetch_api(config))
                fallback_name = {
                    normalize(name): name for name in fallback_boards
                }.get(normalize(record['api_name']))
                variants = fallback_boards.get(fallback_name, [])
            if variants:
                actual_name = variants[0]['name'].strip()
                record['api_name'] = actual_name
                record['variants'] = group_by_board(variants).get(actual_name, [])
                boards[actual_name] = record['variants']
    else:
        boards = group_by_board(fetch_api(config))
        by_normalized = {normalize(name): name for name in boards}
        for record in records:
            actual_name = by_normalized.get(normalize(record['api_name']))
            if actual_name:
                record['api_name'] = actual_name
                record['variants'] = boards[actual_name]

    for record in records:
        record['results'] = {}
        if record['excluded'] or not record['variants']:
            continue
        for lang, path in record['paths'].items():
            record['results'][lang] = analyze(path, lang, record['variants'], config)
    return boards, records


