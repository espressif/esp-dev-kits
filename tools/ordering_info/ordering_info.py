def display_width(text):
    return sum(2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in text)


def memory_cell(value):
    value = (value or '').strip()
    if not value or value.upper() == 'N/A':
        return EMPTY_CELL
    if re.fullmatch(r'\d+', value):
        return f'{value} MB'
    return value


def plain_cell(value):
    value = (value or '').strip()
    if not value or value.upper() == 'N/A':
        return EMPTY_CELL
    return value


def antenna_cell(value, lang, config):
    value = (value or '').strip()
    if not value or value.upper() == 'N/A':
        return EMPTY_CELL
    mapping = config['antenna'].get(value)
    return mapping[lang] if mapping else value


def ordering_code_cell(entry, lang, config):
    code = entry['mpn'].strip()
    suffix = config['status_suffix'].get(entry.get('status'))
    return code + suffix[lang] if suffix else code


def render_rows(variants, lang, config):
    return [[
        ordering_code_cell(entry, lang, config),
        plain_cell(entry.get('moduleName')),
        memory_cell(entry.get('flash')),
        memory_cell(entry.get('psram')),
        antenna_cell(entry.get('antenna'), lang, config),
    ] for entry in variants]


def section_label(folder):
    """RST target for the ordering heading. Unique within one Sphinx build."""
    return f'ordering-info-{folder}'


def render_inc(variants, lang, config, underline_char, folder):
    """Render the full RST content for the .inc file."""
    text = TEXT[lang]
    rows = render_rows(variants, lang, config)
    heading = text['heading']

    # The target has to sit on this heading. A target in the parent guide,
    # directly before the include, does not give :ref: a title.
    lines = [
        GENERATED_COMMENT.rstrip(),
        '',
        f'.. _{section_label(folder)}:',
        '',
    ]
    lines.extend([
        heading,
        underline_char * display_width(heading),
        '',
        text['intro_one'] if len(rows) == 1 else text['intro_many'],
        '',
        '.. list-table::',
        '   :header-rows: 1',
        f'   :widths: {text["widths"]}',
        '',
    ])
    for row in [text['columns']] + rows:
        lines.append(f'   * - {row[0]}')
        lines.extend(f'     - {cell}' for cell in row[1:])

    lines.append('')
    return '\n'.join(lines)


