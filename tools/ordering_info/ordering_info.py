def analyze(path, lang, variants, config):
    """Classify one guide and compute the desired inc content."""
    text_lines = path.read_text(encoding='utf-8').split('\n')
    inc_path = path.parent / INC_FILENAME

    _, _, retail_uchar = find_heading_ci(text_lines, TEXT[lang]['retail_headings'])
    order_idx, order_uchar = find_exact_heading(text_lines, TEXT[lang]['heading'])
    include_idx = has_include_directive(text_lines)

    # The included table heading is a subsection of Contents and Packaging
    # (level 3 in most guides).  Match the guide's own underline characters.
    underline = order_uchar or retail_uchar or level_underline(heading_hierarchy(text_lines), 3)
    desired_inc = render_inc(variants, lang, config, underline, path.parent.name)

    current_inc = inc_path.read_text(encoding='utf-8') if inc_path.exists() else None
    inc_up_to_date = (current_inc == desired_inc)

    # A hand-written Ordering Information section (not an include of the inc file)
    has_manual = (order_idx is not None and include_idx is None)
    if has_manual:
        body = section_body(text_lines, order_idx)
        manual_diff = diff_manual_table(parse_list_table(body), variants, lang, config)
    else:
        manual_diff = None

    return {
        'path': path,
        'inc_path': inc_path,
        'lang': lang,
        'desired_inc': desired_inc,
        'inc_up_to_date': inc_up_to_date,
        'include_idx': include_idx,
        'has_manual': has_manual,
        'manual_diff': manual_diff,
    }


