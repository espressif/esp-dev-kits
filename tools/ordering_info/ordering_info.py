def heading_hierarchy(lines):
    """Return the underline characters of a document in level order.

    RST derives heading levels from the order in which underline characters
    first appear, so the hierarchy is per-document: one guide may use
    ``= - ^``, another ``= - ~ ^``.  Reusing a character at the wrong depth
    makes Sphinx fail with "Title level inconsistent".
    """
    order = []
    for i, line in enumerate(lines[:-1]):
        if not line.strip():
            continue
        nxt = lines[i + 1].strip()
        if len(nxt) >= 3 and nxt[0] in UNDERLINE_CHARS and set(nxt) == {nxt[0]}:
            if nxt[0] not in order:
                order.append(nxt[0])
    return order


def level_underline(hierarchy, level):
    """Return the underline character for a 1-based heading level.

    If the document is shallower than the requested level, pick the first
    preferred character that the document does not already use.
    """
    if level <= len(hierarchy):
        return hierarchy[level - 1]
    for char in UNDERLINE_CHARS:
        if char not in hierarchy:
            return char
    return '^'


def find_heading_ci(lines, candidates):
    """Find any of the candidate headings (case-insensitive match).
    Returns (index, matched_title, underline_char) or (None, None, None)."""
    cands_lower = {c.lower() for c in candidates}
    for i, line in enumerate(lines[:-1]):
        if line.strip().lower() not in cands_lower:
            continue
        underline = lines[i + 1].strip()
        if len(underline) >= 3 and underline[0] in UNDERLINE_CHARS and set(underline) == {underline[0]}:
            return i, line.strip(), underline[0]
    return None, None, None


def find_exact_heading(lines, title):
    """Find an exact heading. Returns (index, underline_char) or (None, None)."""
    for i, line in enumerate(lines[:-1]):
        if line.strip() != title:
            continue
        underline = lines[i + 1].strip()
        if len(underline) >= 3 and underline[0] in UNDERLINE_CHARS and set(underline) == {underline[0]}:
            return i, underline[0]
    return None, None


def section_body(lines, index):
    """Return lines of a section from heading+2 until the next heading."""
    body = []
    i = index + 2
    while i < len(lines):
        line = lines[i]
        if i + 1 < len(lines):
            nxt = lines[i + 1].strip()
            if (line.strip() and len(nxt) >= 3 and
                    nxt[0] in UNDERLINE_CHARS and set(nxt) == {nxt[0]}):
                break
        body.append(line)
        i += 1
    return body


def parse_list_table(body):
    """Parse the first list-table in a body into rows."""
    try:
        start = next(i for i, l in enumerate(body) if l.strip().startswith('.. list-table::'))
    except StopIteration:
        return []
    rows, cell_indent = [], None
    for line in body[start + 1:]:
        stripped = line.strip()
        if not stripped:
            continue
        if not line.startswith(' '):
            break
        if stripped.startswith('* - '):
            cell_indent = len(line) - len(line.lstrip()) + 2
            rows.append([stripped[4:].strip()])
        elif rows and stripped.startswith('- ') and (len(line) - len(line.lstrip())) == cell_indent:
            rows[-1].append(stripped[2:].strip())
        elif rows and rows[-1]:
            rows[-1][-1] = f'{rows[-1][-1]} {stripped}'.strip()
    return rows


def has_include_directive(lines):
    """Return the line index of the include directive, or None."""
    for i, line in enumerate(lines):
        if line.strip() == INCLUDE_DIRECTIVE:
            return i
    return None


def diff_manual_table(rows, variants, lang, config):
    """Compare a hand-written table with the API; return list of difference notes."""
    if len(rows) < 2:
        return ['could not parse the existing table']
    aliases = COLUMN_ALIASES[lang]
    column_map = {i: aliases[c.strip().lower()]
                  for i, c in enumerate(rows[0]) if c.strip().lower() in aliases}
    unmapped = [c for c in rows[0] if c.strip().lower() not in aliases]
    if 0 not in column_map.values():
        return ['could not identify the part number column']

    code_col = next(i for i, t in column_map.items() if t == 0)

    def key(code):
        return normalize(re.split(r'[（(]', code)[0])

    doc_map = {key(row[code_col]): row for row in rows[1:] if len(row) > code_col}
    api_rows_list = render_rows(variants, lang, config)
    api_map = {key(entry['mpn']): row
               for entry, row in zip(variants, api_rows_list)}

    notes = [f'column not covered by the API: {c}' for c in unmapped]
    for code in sorted(doc_map.keys() - api_map.keys()):
        notes.append(f'only in the guide: {doc_map[code][code_col]}')
    for code in sorted(api_map.keys() - doc_map.keys()):
        notes.append(f'only in the API: {api_map[code][0]}')
    for code in sorted(doc_map.keys() & api_map.keys()):
        doc_row, api_row = doc_map[code], api_map[code]
        for i, target in sorted(column_map.items()):
            if target == 0 or i >= len(doc_row):
                continue
            dc, ac = doc_row[i], api_row[target]
            if dc.replace(' ', '') != ac.replace(' ', ''):
                notes.append(f'{doc_row[code_col]} / {TEXT[lang]["columns"][target]}: '
                             f'guide "{dc}" vs API "{ac}"')
    return notes


