"""Keep the "Ordering Information" table of every dev kit user guide in sync
with the Espressif product API.

Subcommands
-----------
report   Print what each user guide needs, without touching any file.
check    CI mode: fail if an inc file is missing or stale.
         Pass ``--since REF`` to check only boards touched since that git ref.
apply    Write generated ``ordering-info.inc`` files.  Does not edit RST guides.
         Pass ``--board FOLDER`` or ``--since REF`` to update some boards only.
hook     Pre-commit mode: update boards inferred from the provided guide paths.

The generated table for each guide is written to ``ordering-info.inc`` in the
same folder.  Adding ``.. include:: ordering-info.inc`` to the user guide is
done by hand.
"""

