def load_config():
    with open(CONFIG_PATH, encoding='utf-8') as f:
        return json.load(f)


def slim_results(results):
    """Keep only the fields used to generate the ordering information table."""
    slim = []
    for entry in results:
        slim.append({field: entry.get(field, '') for field in API_FIELDS})
    return slim


def fetch_api(config, name=None):
    """Fetch all devkits, or all variants for one exact board name."""
    url = config['api_url']
    if name:
        url += '?' + urllib.parse.urlencode({'name': name})
    request = urllib.request.Request(url, headers={'Accept': 'application/json'})
    try:
        response = urllib.request.urlopen(request, timeout=60)
    except Exception as error:
        raise RuntimeError(f'could not fetch {url}: {error}') from error
    with response:
        payload = json.loads(response.read().decode('utf-8'))
    return slim_results(payload.get('results', []))


def normalize(name):
    return re.sub(r'[^a-z0-9]', '', name.lower())


def group_by_board(results):
    boards = {}
    for entry in results:
        boards.setdefault(entry['name'].strip(), []).append(entry)
    for variants in boards.values():
        variants.sort(key=lambda e: STATUS_ORDER.get(e.get('status'), 99))
    return boards


